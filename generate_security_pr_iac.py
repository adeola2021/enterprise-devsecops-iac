#!/usr/bin/env python3
"""generate_security_pr.py - unified remediation PR generator.

  --mode appsec : your existing Semgrep flow (plug into run_appsec(), unchanged)
  --mode iac    : Checkov/OPA findings -> terraform_autofixer.py -> PR
  --mode all    : both

--local-only commits the branch and writes the PR body to reports/pr_body.md
(no push, no `gh`), for sandboxes or dry runs.
"""
import argparse, datetime, json, shutil, subprocess, sys
from pathlib import Path


def sh(*cmd, check=True):
    return subprocess.run(cmd, check=check, text=True, capture_output=True).stdout.strip()


def run_appsec(args):
    """Hook: call your Phase 6 Semgrep -> patch -> PR flow here."""
    print("[appsec] Phase 6 Semgrep flow not bundled in this repo; skipping.")
    return None


def remediate_iac(args):
    summary_path = "reports/autofix_summary.json"
    cmd = [sys.executable, "terraform_autofixer.py", "--tf-dir", args.tf_dir,
           "--admin-cidr", args.admin_cidr, "--tf-bin", args.tf_bin,
           "--validate-mode", args.validate_mode, "--summary", summary_path]
    if args.kms_key_arn:
        cmd += ["--kms-key-arn", args.kms_key_arn]
    for f in args.iac_findings:
        cmd += ["--findings", f]
    subprocess.run(cmd, check=False)
    return json.loads(Path(summary_path).read_text())


def iac_pr_body(s):
    rows = "\n".join(f"| {r['rule']} | `{r['resource']}` | {r['source']} | {r['status']} | {r['detail']} |"
                     for r in s["results"])
    manual = sorted({(m["resource"], m["detail"]) for m in s["results"] if m["status"] == "manual"})
    check = "`fmt` + `validate`" if s["validate_mode"] == "full" else "`fmt` + HCL syntax parse (offline mode)"
    body = ("## Automated IaC security remediation\n\n"
            "| Rule | Resource | Finding source | Status | Detail |\n|---|---|---|---|---|\n" + rows +
            f"\n\nValidation ({check}): **{'passed' if s['validated'] else 'not run'}**\n"
            f"\nFiles changed: {', '.join(f'`{p}`' for p in s['files_changed'])}\n")
    if manual:
        body += "\n### Needs human review\n" + "\n".join(f"- `{r}`: {d}" for r, d in manual)
    body += ("\n\n### Reviewer checklist\n"
             "- [ ] `--admin-cidr` value is the real bastion/VPN range\n"
             "- [ ] KMS key ARN is real and the bucket's writers have `kms:GenerateDataKey`\n"
             "\n_Generated by terraform_autofixer.py. Review before merging._")
    return body


def open_pr(branch, title, body, paths, local_only):
    sh("git", "checkout", "-b", branch)
    sh("git", "add", *paths)
    sh("git", "-c", "user.name=autofix-bot", "-c", "user.email=autofix@example.com", "commit", "-m", title)
    Path("reports/pr_body.md").write_text(body)
    if local_only or not shutil.which("gh"):
        print(f"[local-only] committed on branch {branch}; PR body -> reports/pr_body.md (no push, no PR)")
        return
    sh("git", "push", "-u", "origin", branch)
    print(sh("gh", "pr", "create", "--title", title, "--body", body, "--label", "security", "--base", "main"))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", choices=["appsec", "iac", "all"], default="all")
    ap.add_argument("--tf-dir", default="terraform/fixture")
    ap.add_argument("--iac-findings", nargs="*", default=["reports/checkov.json", "reports/conftest.json"])
    ap.add_argument("--admin-cidr", default="10.0.0.0/8")
    ap.add_argument("--kms-key-arn")
    ap.add_argument("--tf-bin", default="terraform")
    ap.add_argument("--validate-mode", choices=["full", "offline"], default="full")
    ap.add_argument("--local-only", action="store_true")
    a = ap.parse_args()
    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")

    if a.mode in ("appsec", "all"):
        run_appsec(a)

    if a.mode in ("iac", "all"):
        s = remediate_iac(a)
        if s["validated"] and s["files_changed"]:
            open_pr(f"autofix/iac-{stamp}", "fix(iac): remediate Checkov/OPA violations",
                    iac_pr_body(s), s["files_changed"], a.local_only)
        elif s["validated"] is False:
            sys.exit("Autofix failed validation (changes rolled back); no PR opened.")
        else:
            print("No auto-fixable IaC findings.")


if __name__ == "__main__":
    main()
