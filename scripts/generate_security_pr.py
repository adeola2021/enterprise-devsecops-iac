#!/usr/bin/env python3
"""Open a remediation PR for auto-fixable Semgrep findings.

Auto-fixes weak hashes (MD5/SHA1 -> SHA-256) in Python and Node.js.
Everything else is listed in the PR body as report-only.
Token: GITHUB_TOKEN env var (never pass it on the command line).
"""
import argparse
import datetime
import difflib
import json
import os
import re
import subprocess
import sys

PY_FIXES = [
    (re.compile(r"\bhashlib\.(?:md5|sha1)\("), "hashlib.sha256("),
    (re.compile(r"""\bhashlib\.new\(\s*(["'])(?:md5|sha1)\1"""),
     r"hashlib.new(\g<1>sha256\g<1>"),
]
JS_FIXES = [
    (re.compile(r"""\bcreateHash\(\s*(["'])(?:md5|sha1)\1\s*\)"""),
     r"createHash(\g<1>sha256\g<1>)"),
]
FIXERS = {
    "sec002-python-weak-hash": PY_FIXES,
    "sec002-nodejs-weak-hash": JS_FIXES,
}


def sh(*cmd):
    return subprocess.check_output(cmd, text=True).strip()


def rule_name(finding):
    return finding["check_id"].split(".")[-1]


def meta(finding, key):
    val = finding.get("extra", {}).get("metadata", {}).get(key, "")
    return ", ".join(val) if isinstance(val, list) else str(val)


def apply_fix(text, line_no, patterns):
    lines = text.splitlines(keepends=True)
    old = lines[line_no - 1]
    new = old
    for rx, repl in patterns:
        new = rx.sub(repl, new)
    if new == old:
        return text, False
    lines[line_no - 1] = new
    return "".join(lines), True


def table(rows):
    out = ["| Rule | File | Line | Severity | CWE |", "|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| `{rule_name(r)}` | `{r['path']}` | {r['start']['line']} | "
                   f"{meta(r, 'security_severity')} | {meta(r, 'cwe')} |")
    return "\n".join(out)


def analyse(report_path, read_text):
    """Return (changes, fixed_rows, report_only). changes: {path: (old, new)}."""
    with open(report_path) as f:
        data = json.load(f)
    errs = [e for e in data.get("errors", []) if e.get("level") == "error"]
    if errs:
        sys.exit(f"Report has Semgrep errors, refusing to continue: {errs[0].get('message')}")

    by_file, report_only = {}, []
    for r in data.get("results", []):
        if rule_name(r) in FIXERS:
            by_file.setdefault(r["path"], []).append(r)
        else:
            report_only.append(r)

    changes, fixed_rows = {}, []
    for path, items in by_file.items():
        old_text = read_text(path)
        new_text = old_text
        for r in items:
            new_text, ok = apply_fix(new_text, r["start"]["line"], FIXERS[rule_name(r)])
            (fixed_rows if ok else report_only).append(r)
        if new_text != old_text:
            changes[path] = (old_text, new_text)
    return changes, fixed_rows, report_only


def build_body(fixed_rows, report_only):
    body = ["## Automated security remediation", "",
            "Generated by `scripts/generate_security_pr.py` from the Semgrep AppSec report.", ""]
    if fixed_rows:
        body += ["### Patched automatically (MD5/SHA1 to SHA-256)", table(fixed_rows), "",
                 "**Review before merging:** SHA-256 produces different output. Code that "
                 "compares against stored hashes, external checksums or fixed-length columns "
                 "may break. For password storage use bcrypt, scrypt or Argon2.", ""]
    if report_only:
        body += ["### Needs manual remediation (not changed)", table(report_only), "",
                 "SQL injection, deserialization, subprocess and credential fixes change "
                 "behaviour and are not safe to automate."]
    return "\n".join(body)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--report", default="reports/phase6/semgrep-appsec.json")
    ap.add_argument("--base", default=None, help="base branch (default: current)")
    ap.add_argument("--repo", default=None, help="owner/name (default: from origin)")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    base = args.base or sh("git", "branch", "--show-current")
    repo_name = args.repo
    if not repo_name:
        url = sh("git", "remote", "get-url", "origin")
        m = re.search(r"github\.com[:/](.+?)(?:\.git)?$", url)
        if not m:
            sys.exit("Cannot work out owner/name from origin; use --repo")
        repo_name = m.group(1)

    gh_repo = None
    if args.dry_run:
        def read_text(path):
            with open(path) as fh:
                return fh.read()
    else:
        token = os.environ.get("GITHUB_TOKEN")
        if not token:
            sys.exit("GITHUB_TOKEN is not set (or use --dry-run).")
        from github import Auth, Github
        gh_repo = Github(auth=Auth.Token(token)).get_repo(repo_name)

        def read_text(path):
            return gh_repo.get_contents(path, ref=base).decoded_content.decode()

    changes, fixed_rows, report_only = analyse(args.report, read_text)
    print(f"Auto-fixable findings: {len(fixed_rows)} | Report-only: {len(report_only)}")
    for target, (old, new) in changes.items():
        print("\n".join(difflib.unified_diff(
            old.splitlines(), new.splitlines(),
            f"a/{target}", f"b/{target}", lineterm="")))

    body = build_body(fixed_rows, report_only)
    if not changes:
        print("No auto-fixable changes, so no PR is created.")
        return
    if args.dry_run:
        print("\n--- DRY RUN: PR body ---\n" + body)
        return

    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%d%H%M%S")
    branch = f"security/semgrep-autofix-{stamp}"
    gh_repo.create_git_ref(ref=f"refs/heads/{branch}",
                           sha=gh_repo.get_branch(base).commit.sha)
    for target, (_, new_text) in changes.items():
        sha = gh_repo.get_contents(target, ref=branch).sha
        gh_repo.update_file(target, f"security: replace weak hash with SHA-256 in {target}",
                            new_text, sha, branch=branch)
    pr = gh_repo.create_pull(title="Security: replace weak hashing (Semgrep autofix)",
                             body=body, head=branch, base=base)
    print(f"Created PR: {pr.html_url}")


if __name__ == "__main__":
    main()
