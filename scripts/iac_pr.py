"""IaC remediation flow used by generate_security_pr.py (--mode iac)."""
import datetime
import json
import subprocess
import sys
from pathlib import Path


def sh(*cmd):
    return subprocess.run(cmd, check=True, text=True, capture_output=True).stdout.strip()


def remediate(args):
    Path("reports").mkdir(exist_ok=True)
    summary_path = "reports/autofix_summary.json"
    cmd = [sys.executable, "terraform_autofixer.py", "--tf-dir", args.tf_dir,
           "--admin-cidr", args.admin_cidr, "--tf-bin", args.tf_bin,
           "--validate-mode", args.validate_mode, "--summary", summary_path]
    if args.kms_key_arn:
        cmd += ["--kms-key-arn", args.kms_key_arn]
    for f in args.iac_findings:
        cmd += ["--findings", f]
    rc = subprocess.run(cmd).returncode
    return rc, json.loads(Path(summary_path).read_text())


def pr_body(s):
    rows = "\n".join(
        f"| {r['rule']} | `{r['resource']}` | {r['source']} | {r['status']} | {r['detail']} |"
        for r in s["results"])
    manual = sorted({(m["resource"], m["detail"]) for m in s["results"] if m["status"] == "manual"})
    check = "`fmt` + `validate`" if s["validate_mode"] == "full" else "`fmt` + HCL syntax parse"
    body = ("## Automated IaC security remediation\n\n"
            "| Rule | Resource | Finding source | Status | Detail |\n|---|---|---|---|---|\n"
            + rows + f"\n\nValidation ({check}): **{'passed' if s['validated'] else 'not run'}**\n"
            + "\nFiles changed: " + ", ".join(f"`{p}`" for p in s["files_changed"]) + "\n")
    if manual:
        body += "\n### Needs human review (not auto-fixed)\n"
        body += "\n".join(f"- `{r}`: {d}" for r, d in manual) + "\n"
    body += ("\n### Reviewer checklist\n"
             "- [ ] Admin CIDR is the real bastion/VPN range\n"
             "- [ ] KMS key ARN is real (the fixture uses a placeholder)\n"
             "- [ ] IAM wildcard policies rewritten by a human\n"
             "\n_Generated by terraform_autofixer.py. Review before merging._")
    return body


def run_iac(args, base):
    if sh("git", "status", "--porcelain", "--", args.tf_dir):
        sys.exit(f"{args.tf_dir} has uncommitted changes; commit or discard them first.")
    if sh("git", "diff", "--cached", "--name-only"):
        sys.exit("Index has staged changes; commit or unstage them first.")
    rc, summary = remediate(args)
    if rc != 0:
        sys.exit("terraform_autofixer.py failed; nothing committed.")
    files = summary["files_changed"]
    if not files:
        print("No auto-fixable IaC changes, so no PR is created.")
        return
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%d%H%M%S")
    branch = f"security/iac-autofix-{stamp}"
    title = "Security: remediate Checkov/OPA IaC findings (autofix)"
    body = pr_body(summary)
    Path("reports/pr_body.md").write_text(body)
    sh("git", "checkout", "-b", branch)
    sh("git", "add", *files)
    sh("git", "-c", "user.name=autofix-bot", "-c", "user.email=autofix@example.com",
       "commit", "-m", title, "--", *files)
    if args.local_only:
        print(f"[local-only] committed on {branch}; PR body in reports/pr_body.md")
    else:
        sh("git", "push", "-u", "origin", branch)
        print(sh("gh", "pr", "create", "--title", title, "--body-file",
                 "reports/pr_body.md", "--base", base, "--head", branch))
    sh("git", "checkout", base)
